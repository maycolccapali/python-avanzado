# crear un programa que mepermita desarrollar las 4 operaciones basicas(suma,resta,division,multiplicacion)



def suma(a, b):
    return a + b


def resta(a, b):
    return a - b


def multiplicacion(a, b):
    return a * b


def division(a, b):
    return a / b


# Números
num1 = 10
num2 = 5

# Resultados
print("Suma:", suma(num1, num2))
print("Resta:", resta(num1, num2))
print("Multiplicación:", multiplicacion(num1, num2))
print("División:", division(num1, num2))